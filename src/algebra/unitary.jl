"""Marker stored by a unitary transformation whose rules are time independent."""
struct StaticTime end

"""Marker stored by a unitary transformation differentiated with respect to `variable`."""
struct DynamicTime
    variable::Num
end

@enum AffineStructure::UInt8 begin
    AFFINE_BOSONIC_NAMBU
    AFFINE_SYMPLECTIC_PHASE_SPACE
    AFFINE_ORTHOGONAL
    AFFINE_UNITARY_LINEAR
    AFFINE_NONE
end

struct AffineBlock
    structure::AffineStructure
    basis::Vector{Op}
    linear::Matrix{CNum}
    shift::Vector{CNum}
end

struct AffineAction
    blocks::Vector{AffineBlock}
    relations::Vector{ParamRelation}
end

"""
    UnitaryTransform(G, θ)
    inv(U)
    U1 * U2

Exact change of frame generated by a Hermitian operator.

`UnitaryTransform(G, θ)` is the transformation ``U = e^{-i\\theta G}``. The image of each
operator follows in closed form when the commutators with `G` close on a finite set of
operators and their exponential is known exactly, as for displacements, phase rotations,
beam splitters and squeezers with numeric rates; otherwise an `ArgumentError` is thrown.
The named constructors [`Displace`](@ref), [`Rotation`](@ref), [`Squeeze`](@ref),
[`Bogoliubov`](@ref), [`RotatingFrame`](@ref) and [`DisplacementFrame`](@ref) cover the
common frames, also with symbolic parameters.

`inv(U)` is the inverse transformation, and in a product `U1 * U2` the left factor is
applied first. Parameters of a transformation are replaced with [`substitute`](@ref).

# Examples
```jldoctest
julia> a = Destroy(FockSpace(:cavity), :a);

julia> @variables θ;

julia> conjugate(a, UnitaryTransform(a' * a, θ))
exp(-im*θ) * a

julia> conjugate(a, Displace(a, 1//2) * Rotation(a, θ))
1//2 + exp(-im*θ) * a
```

See also [`conjugate`](@ref), [`transform`](@ref), [`generators`](@ref).
"""
struct UnitaryTransform{T}
    action::AffineAction
    rules::Dict{Op, QAdd}
    generators::Vector{Op}
    gauge::QAdd
    time::T

    function UnitaryTransform{T}(
            action::AffineAction, rules::Dict{Op, QAdd}, generators::Vector{Op},
            gauge::QAdd, time::T,
        ) where {T}
        (T === StaticTime || T === DynamicTime) ||
            throw(ArgumentError("invalid unitary-transform time marker `$T`"))
        return new{T}(action, rules, generators, gauge, time)
    end
end

@noinline unitary_error(message::AbstractString) = throw(ArgumentError(message))

is_fock(o::Op) = is_destroy(o) || is_create(o)
is_phase_space(o::Op) = is_position(o) || is_momentum(o)
lowering(o::Op) = is_create(o) ? adjoint(o) : o

function fock_or_throw(o::Op, what::AbstractString)
    is_fock(o) || unitary_error("$what expects a Fock ladder operator, got $(o.kind)")
    return lowering(o)
end

function site_generators(o::Op)
    if is_fock(o)
        d = lowering(o)
        return Op[d, adjoint(d)]
    elseif is_pauli(o) || is_spin(o)
        return Op[
            with_levels(o, axis, 0)
                for axis in 1:3
        ]
    elseif is_transition(o)
        n = Int(o.nlev)
        return Op[
            with_levels(o, i, j)
                for i in 1:n for j in 1:n
        ]
    end
    return Op[]
end

function validate_complete(generators::Vector{Op})
    available = Set(generators)
    checked = Set{SiteKey}()
    for first_generator in generators
        key = site_key(first_generator)
        key in checked && continue
        push!(checked, key)
        if is_phase_space(first_generator)
            on_site(kind) = any(g -> site_key(g) == key && kind(g), generators)
            (on_site(is_position) && on_site(is_momentum)) || unitary_error(
                "incomplete rule set: `$first_generator` has no rule for its conjugate variable",
            )
        end
        for generator in site_generators(first_generator)
            generator in available || unitary_error(
                "incomplete rule set: `$first_generator` is covered but `$generator` is not",
            )
        end
    end
    return generators
end

is_free_family(o::Op) = has_index(o.index) && iszero(index_slot(o.index))

coefficient_is_real(c::CNum) = isequal(c, conj(c))

qadd_depends_on(q::QAdd, variable) = any(((_, c),) -> coefficient_depends_on(c, variable), q)

function validated_transform(
        action::AffineAction, gauge::QAdd, time::T,
    ) where {T <: Union{StaticTime, DynamicTime}}
    rules = affine_rules(action)
    generators = sort!(collect(keys(rules)))
    for generator in generators
        is_free_family(generator) && unitary_error(
            "unitary transforms of free indexed-operator families are not part of " *
                "the exact closed-form API; resolve the index to one site first",
        )
    end
    validate_complete(generators)
    return UnitaryTransform{T}(action, rules, generators, gauge, time)
end

function time_or_throw(t::Num)
    raw = SymbolicUtils.unwrap(t)
    SymbolicUtils.issym(raw) || unitary_error(
        "time must be a real symbolic variable, got `$t`",
    )
    return t
end

function timed_transform(U::UnitaryTransform{StaticTime}, gauge::QAdd, t::Num)
    time = DynamicTime(time_or_throw(t))
    reduced = reduce_params(gauge, U.action.relations, true)
    return UnitaryTransform{DynamicTime}(U.action, U.rules, U.generators, reduced, time)
end

function covered_site(U::UnitaryTransform, key::SiteKey)
    for generator in U.generators
        site_key(generator) == key && return true
    end
    return false
end

function validate_coverage(q::QAdd, U::UnitaryTransform)
    for (term, _) in q, operator in term.ops
        haskey(U.rules, operator) && continue
        covered_site(U, site_key(operator)) || continue
        unitary_error(
            "`$operator` acts on a site covered by this transform but has no rule; " *
                "the constructor must cover every generator of a transformed site",
        )
    end
    return q
end

apply_rules(q::QAdd, rules::Dict{Op, QAdd}) = substitute_with(q, SubstitutionRules(rules))

function reduce_params(q::QAdd, relations::Vector{ParamRelation}, gated::Bool)
    isempty(relations) && return q
    scratch = ParamRelation[]
    return map_coefficients(c -> reduce_all(c, relations, gated, scratch), q)
end

"""
    conjugate(A, U::UnitaryTransform)
    conjugate(L, U::UnitaryTransform)

Image of an operator expression under a unitary transformation.

The result is ``U^\\dagger A U``, with every operator replaced by its exact image; no
series is truncated. Formal operator functions are transformed through their arguments.
For a [`Lindbladian`](@ref) or a superoperator `L`, every operator it contains is
conjugated, so a channel ``\\mathcal{D}[J]`` becomes ``\\mathcal{D}[U^\\dagger J U]``.
For a Hamiltonian in a time-dependent frame use [`transform`](@ref), which adds the term
from the motion of the frame.

# Examples
```jldoctest
julia> a = Destroy(FockSpace(:cavity), :a);

julia> @variables α::Number;

julia> conjugate(a' * a, Displace(a, α))
conj(α)*α + conj(α) * a + α * a' + a' * a
```

See also [`transform`](@ref), [`UnitaryTransform`](@ref).
"""
function conjugate(q::QAdd, U::UnitaryTransform)
    validate_coverage(q, U)
    return reduce_params(apply_rules(q, U.rules), U.action.relations, true)
end

conjugate(o::QSym, U::UnitaryTransform) =
    conjugate(to_qadd(o), U)

"""
    transform(H, U::UnitaryTransform)
    transform(L, U::UnitaryTransform)

Hamiltonian in the frame of a unitary transformation.

The result is ``U^\\dagger H U + i (\\partial_t U^\\dagger) U``. The second term, returned by
[`gauge_term`](@ref), comes from the motion of a time-dependent frame. For a static
transformation it vanishes and `transform` agrees with [`conjugate`](@ref). For a
[`Lindbladian`](@ref) `L`, the Hamiltonian is transformed and every jump is conjugated.

QuantumOpticsBase also exports a `transform`. With both packages loaded, import the name
explicitly, `using SecondQuantizedAlgebra: transform`, or qualify it.

# Examples
```jldoctest
julia> a = Destroy(FockSpace(:cavity), :a);

julia> @variables ω g t;

julia> transform(ω * a' * a + g * (a + a'), Rotation(a, ω * t, t))
exp(-im*t*ω)*g * a + exp(im*t*ω)*g * a'
```

See also [`conjugate`](@ref), [`gauge_term`](@ref), [`RotatingFrame`](@ref).
"""
transform(q::QAdd, U::UnitaryTransform{StaticTime}) = conjugate(q, U)
transform(q::QAdd, U::UnitaryTransform{DynamicTime}) = conjugate(q, U) + U.gauge
transform(o::QSym, U::UnitaryTransform) =
    transform(to_qadd(o), U)

conjugate(q::QExpr, U::UnitaryTransform)::QExpr = map_args(
    arg -> conjugate(arg, U), q, reduce_affine(q.coeff, U.action.relations, ParamRelation[]),
)

transform(q::QExpr, U::UnitaryTransform{StaticTime}) = conjugate(q, U)
transform(q::QExpr, U::UnitaryTransform{DynamicTime}) = conjugate(q, U) + U.gauge

"""
    gauge_term(U::UnitaryTransform)

Term that the motion of a time-dependent frame adds to a Hamiltonian.

It is ``i (\\partial_t U^\\dagger) U``, zero for a static transformation. [`transform`](@ref)
adds it automatically.

# Examples
```jldoctest
julia> a = Destroy(FockSpace(:cavity), :a);

julia> @variables ω t;

julia> gauge_term(Rotation(a, ω * t, t))
-ω * a' * a
```

See also [`transform`](@ref).
"""
gauge_term(U::UnitaryTransform) = U.gauge

"""
    generators(U::UnitaryTransform)

Operators that the transformation `U` acts on, in canonical order.

# Examples
```jldoctest
julia> h = FockSpace(:a) ⊗ FockSpace(:b);

julia> @qnumbers a::Destroy(h, 1) b::Destroy(h, 2);

julia> @variables θ;

julia> generators(Rotation(a, b, θ))
4-element Vector{Op}:
 a
 a'
 b
 b'
```

See also [`UnitaryTransform`](@ref).
"""
generators(U::UnitaryTransform) = copy(U.generators)

"""
    displacement(U::UnitaryTransform, o::Op)

Return the c-number part of [`conjugate(o, U)`](@ref conjugate) for a Fock or phase-space
operator `o`: `α` for `conjugate(a, U) = L(a) + α` with `L` linear. For a moving frame the
result is the time-dependent amplitude; a site `U` does not act on gives zero.
"""
function displacement(U::UnitaryTransform, o::Op)
    is_fock(o) || is_phase_space(o) || unitary_error(
        "`displacement` needs a Fock or phase-space operator, got `$o`",
    )
    for (term, c) in conjugate(o, U).arguments
        isempty(term.ops) && return c
    end
    return CNUM_ZERO
end

function Base.inv(U::UnitaryTransform{T}) where {T}
    inverse_action = canonical_affine_inverse(U.action)
    inverse_rules = affine_rules(inverse_action)
    relations = U.action.relations
    gauge = if T === StaticTime || iszero(U.gauge)
        U.gauge
    else
        -reduce_params(apply_rules(U.gauge, inverse_rules), relations, true)
    end
    return UnitaryTransform{T}(
        inverse_action, inverse_rules, U.generators, gauge, U.time,
    )
end

Base.adjoint(U::UnitaryTransform) = inv(U)

function contains_relation(relations::Vector{ParamRelation}, relation::ParamRelation)
    for existing in relations
        isequal(existing.hi, relation.hi) && isequal(existing.lo, relation.lo) &&
            existing.sign == relation.sign && return true
    end
    return false
end

function push_relation!(relations::Vector{ParamRelation}, relation::ParamRelation)
    contains_relation(relations, relation) || push!(relations, relation)
    return relations
end

function merge_relations(a::Vector{ParamRelation}, b::Vector{ParamRelation})
    isempty(a) && return b
    all(relation -> contains_relation(a, relation), b) && return a
    out = copy(a)
    for relation in b
        push_relation!(out, relation)
    end
    return out
end

function add_gauges(left::QAdd, right::QAdd)
    if isempty(left.indices) && isempty(right.indices) &&
            length(left.arguments) == length(right.arguments) == 1
        first_term, first_coefficient = first(left.arguments)
        second_term, second_coefficient = first(right.arguments)
        if isequal(first_term, second_term)
            coefficient = first_coefficient + second_coefficient
            iszero(coefficient) && return zero_qadd()
            return QAdd(QTermDict(first_term => coefficient), EMPTY_INDICES)
        end
    end
    return left + right
end


rules_depend_on(U::UnitaryTransform{StaticTime}, t::Num) =
    any(image -> qadd_depends_on(image, SymbolicUtils.unwrap(t)), values(U.rules))

function check_adopted_time(U::UnitaryTransform{StaticTime}, t::Num)
    rules_depend_on(U, t) && unitary_error(
        "a static transform whose rules depend on `$t` cannot be composed with a timed " *
            "transform; construct the moving transform with its timed constructor",
    )
    return U
end

function compose(
        first::UnitaryTransform, second::UnitaryTransform, time::T,
    ) where {T <: Union{StaticTime, DynamicTime}}
    relations = merge_relations(first.action.relations, second.action.relations)
    action = compose_action(first.action, second.action, relations)
    rules = affine_rules(action)

    gauge = if iszero(first.gauge)
        second.gauge
    else
        transported = reduce_params(
            apply_rules(first.gauge, second.rules), relations, true,
        )
        iszero(second.gauge) ? transported : add_gauges(transported, second.gauge)
    end

    same_layout = length(rules) == length(first.rules) && all(in(keys(rules)), first.generators)
    generators = same_layout ? first.generators : sort!(collect(keys(rules)))
    return UnitaryTransform{T}(action, rules, generators, gauge, time)
end

composed_time(::UnitaryTransform{StaticTime}, ::UnitaryTransform{StaticTime}) = StaticTime()

function composed_time(first::UnitaryTransform{StaticTime}, second::UnitaryTransform{DynamicTime})
    check_adopted_time(first, second.time.variable)
    return second.time
end

function composed_time(first::UnitaryTransform{DynamicTime}, second::UnitaryTransform{StaticTime})
    check_adopted_time(second, first.time.variable)
    return first.time
end

function composed_time(first::UnitaryTransform{DynamicTime}, second::UnitaryTransform{DynamicTime})
    isequal(first.time.variable, second.time.variable) || unitary_error(
        "cannot compose transforms with different time variables " *
            "(`$(first.time.variable)` and `$(second.time.variable)`)",
    )
    return first.time
end

Base.:*(first::UnitaryTransform, second::UnitaryTransform) =
    compose(first, second, composed_time(first, second))

function rule_qadd(pairs::Vector{Tuple{CNum, Vector{Op}}})
    out = QTermDict()
    for (coefficient, operators) in pairs
        iszero(coefficient) || addto!(out, operators, coefficient)
    end
    return QAdd(out, EMPTY_INDICES)
end

rule_qadd(pairs::Vararg{Tuple{CNum, Vector{Op}}}) =
    rule_qadd(Tuple{CNum, Vector{Op}}[pairs...])
scaled(coefficient::CNum, operator::Op) = rule_qadd((coefficient, Op[operator]))

phase(ϕ::Real) = phase_coeff(as_num(ϕ))
conj_phase(ϕ::Real) = conj(phase(ϕ))
trig_rel(θ::Real) = ParamRelation(cos(θ), sin(θ), -1)
hyp_rel(r::Real) = ParamRelation(cosh(r), sinh(r), 1)

dt(c::CNum, t::Num) = Symbolics.derivative(c, t)
dt(x::Coefficient, t::Num) = dt(to_cnum(x), t)

gauge(generator::QAdd, θ::Real, t::Num) = generator * (-dt(θ, t))
